import jsPDF from "jspdf";

const n = value => Number(value) || 0;
const money = value => "INR " + n(value).toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const clean = value => String(value ?? "").replace(/[\\r\\n]+/g, " ").trim();
const date = value => {
  if (!value) return "—";
  const parsed = new Date(value + "T00:00:00");
  return Number.isNaN(parsed.getTime()) ? String(value) : parsed.toLocaleDateString("en-IN", { day: "2-digit", month: "short", year: "numeric" });
};

export function createQuotationPdf({ document, items = [], company = {} }) {
  const pdf = new jsPDF({ unit: "mm", format: "a4" });
  const width = pdf.internal.pageSize.getWidth();
  const height = pdf.internal.pageSize.getHeight();
  const margin = 14;
  const contentWidth = width - margin * 2;
  let y = 17;
  let page = 1;

  const setText = (size = 9, style = "normal", color = [42, 55, 73]) => {
    pdf.setFont("helvetica", style);
    pdf.setFontSize(size);
    pdf.setTextColor(...color);
  };
  const footer = () => {
    pdf.setDrawColor(220, 228, 237);
    pdf.line(margin, height - 13, width - margin, height - 13);
    setText(7, "normal", [115, 128, 146]);
    pdf.text("Generated by SYD Billing & Accounting", margin, height - 8);
    pdf.text("Page " + page, width - margin, height - 8, { align: "right" });
  };
  const newPage = () => {
    footer();
    pdf.addPage();
    page += 1;
    y = 17;
  };
  const ensureSpace = amount => {
    if (y + amount > height - 20) newPage();
  };
  const drawTableHeader = () => {
    pdf.setFillColor(235, 242, 251);
    pdf.roundedRect(margin, y, contentWidth, 9, 1.5, 1.5, "F");
    setText(7.5, "bold", [38, 58, 83]);
    pdf.text("#", margin + 2, y + 6);
    pdf.text("Item / Description", margin + 10, y + 6);
    pdf.text("Qty", margin + 112, y + 6, { align: "right" });
    pdf.text("Rate", margin + 139, y + 6, { align: "right" });
    pdf.text("GST / CESS", margin + 159, y + 6, { align: "right" });
    pdf.text("Amount", width - margin - 2, y + 6, { align: "right" });
    y += 13;
  };

  // Company identity
  setText(16, "bold", [18, 39, 68]);
  pdf.text(clean(company.company_name || "Company"), margin, y);
  y += 6;
  setText(8, "normal", [85, 101, 122]);
  const address = clean(company.address);
  if (address) {
    const addressLines = pdf.splitTextToSize(address, contentWidth);
    pdf.text(addressLines, margin, y);
    y += addressLines.length * 4 + 1;
  }
  const companyMeta = [
    company.gstin ? "GSTIN: " + clean(company.gstin) : "",
    company.pan ? "PAN: " + clean(company.pan) : "",
    company.mobile ? "Mobile: " + clean(company.mobile) : "",
    company.email ? "Email: " + clean(company.email) : "",
  ].filter(Boolean).join("   |   ");
  if (companyMeta) {
    const metaLines = pdf.splitTextToSize(companyMeta, contentWidth);
    pdf.text(metaLines, margin, y);
    y += metaLines.length * 4 + 2;
  } else {
    y += 3;
  }

  // Document title
  pdf.setFillColor(18, 57, 102);
  pdf.roundedRect(margin, y, contentWidth, 13, 2, 2, "F");
  setText(14, "bold", [255, 255, 255]);
  pdf.text("QUOTATION", width / 2, y + 8.5, { align: "center" });
  y += 21;

  // Document and customer details
  const detailTop = y;
  setText(8.5, "bold", [38, 58, 83]);
  pdf.text("Quotation No.", margin, y);
  pdf.text("Date", width / 2 + 4, y);
  setText(9, "normal", [42, 55, 73]);
  pdf.text(clean(document.invoice_no || "—"), margin, y + 5);
  pdf.text(date(document.invoice_date), width / 2 + 4, y + 5);
  y += 14;
  setText(8.5, "bold", [38, 58, 83]);
  pdf.text("Quotation For", margin, y);
  pdf.text("Valid Until", width / 2 + 4, y);
  setText(9, "normal", [42, 55, 73]);
  pdf.text(clean(document.customer_name || "—"), margin, y + 5);
  pdf.text(date(document.valid_until), width / 2 + 4, y + 5);
  y += 13;
  setText(7.5, "normal", [100, 113, 131]);
  pdf.text("Rate mode: " + (document.tax_inclusive ? "Tax inclusive" : "Tax exclusive"), margin, y);
  y += 9;

  drawTableHeader();
  (items || []).forEach((item, index) => {
    const description = pdf.splitTextToSize(clean(item.item_name || item.particulars || item.description || "—"), 88);
    const rowHeight = Math.max(9, description.length * 4 + 3);
    if (y + rowHeight > height - 24) {
      newPage();
      drawTableHeader();
    }
    setText(7.5, "normal", [42, 55, 73]);
    pdf.text(String(index + 1), margin + 2, y + 2);
    pdf.text(description, margin + 10, y + 2);
    pdf.text(String(n(item.qty)), margin + 112, y + 2, { align: "right" });
    pdf.text(money(item.rate), margin + 139, y + 2, { align: "right" });
    pdf.text(n(item.gst_rate) + "% / " + n(item.cess_rate) + "%", margin + 159, y + 2, { align: "right" });
    pdf.text(money(item.amount), width - margin - 2, y + 2, { align: "right" });
    y += rowHeight;
    pdf.setDrawColor(225, 231, 239);
    pdf.line(margin, y, width - margin, y);
    y += 2;
  });

  y += 5;
  const totals = [
    ["Taxable Value", document.taxable_value],
    ["CGST", document.cgst],
    ["SGST", document.sgst],
    ["IGST", document.igst],
    ["CESS", document.cess_amount],
  ];
  totals.forEach(([label, value]) => {
    ensureSpace(7);
    setText(8.5, "normal", [65, 78, 96]);
    pdf.text(label, width - margin - 65, y);
    pdf.text(money(value), width - margin, y, { align: "right" });
    y += 6;
  });
  ensureSpace(14);
  pdf.setFillColor(237, 243, 251);
  pdf.roundedRect(width - margin - 83, y - 1, 83, 12, 1.5, 1.5, "F");
  setText(10.5, "bold", [18, 57, 102]);
  pdf.text("Grand Total", width - margin - 79, y + 7);
  pdf.text(money(document.total_amount), width - margin - 3, y + 7, { align: "right" });
  y += 20;

  ensureSpace(23);
  setText(8, "bold", [42, 55, 73]);
  pdf.text("Terms & Notes", margin, y);
  y += 5;
  setText(7.5, "normal", [100, 113, 131]);
  pdf.text("This quotation is valid until the date stated above and is not a tax invoice.", margin, y);
  y += 13;
  pdf.setDrawColor(185, 195, 207);
  pdf.line(width - margin - 55, y, width - margin, y);
  setText(7.5, "normal", [100, 113, 131]);
  pdf.text("Authorized Signatory", width - margin, y + 5, { align: "right" });

  for (let p = 1; p <= pdf.getNumberOfPages(); p += 1) {
    pdf.setPage(p);
    footer();
  }

  const fileName = String(document.invoice_no || "quotation").replace(/[^a-z0-9._-]/gi, "_") + ".pdf";
  return { blob: pdf.output("blob"), fileName };
}
